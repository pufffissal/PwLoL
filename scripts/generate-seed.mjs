// Generates supabase/migrations/*_seed_regions.sql from src/data/regions.ts
// Usage: npm run seed:sql   (Node 22.18+ runs .ts files natively)
import { writeFileSync } from 'node:fs';
import { REGIONS } from '../src/data/regions.ts';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;

const rows = REGIONS.map(
  (r, i) =>
    `  (${[q(r.id), q(r.name), q(r.epithet), q(r.tagline), q(r.icon), q(r.accent[0]), q(r.accent[1]), q(r.capital), q(r.governance), q(r.magicStance), arr(r.champions), r.featured ? 'true' : 'false', `${q(JSON.stringify(r.sections))}::jsonb`, i].join(', ')})`,
);

const sql = `-- GENERATED by scripts/generate-seed.mjs from src/data/regions.ts. Do not edit by hand.
insert into public.regions
  (id, name, epithet, tagline, icon, accent_from, accent_to, capital, governance, magic_stance, champions, featured, sections, sort_order)
values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, epithet = excluded.epithet, tagline = excluded.tagline, icon = excluded.icon,
  accent_from = excluded.accent_from, accent_to = excluded.accent_to, capital = excluded.capital,
  governance = excluded.governance, magic_stance = excluded.magic_stance, champions = excluded.champions,
  featured = excluded.featured, sections = excluded.sections, sort_order = excluded.sort_order, updated_at = now();
`;

writeFileSync(new URL('../supabase/migrations/20261111000002_seed_regions.sql', import.meta.url), sql);
console.log(`Wrote ${REGIONS.length} regions`);
